"""Experiment endpoints: registry browsing, config schema, run, and sweep."""

from __future__ import annotations

from typing import Any

from fastapi import APIRouter, HTTPException

from src.engine.api import run as engine_run, sweep as engine_sweep
from src.engine.models import ExperimentConfig, ExperimentResult, SweepManifest
from src.experiments import get_experiment, list_experiments

router = APIRouter()


# ── Registry ────────────────────────────────────────────────────────────


@router.get("")
def list_all() -> list[dict[str, str]]:
    """List every registered experiment (name + description)."""
    return [{"name": n, "description": d} for n, d in list_experiments()]


@router.get("/config-schema")
def config_schema() -> dict[str, Any]:
    """Return the JSON Schema for ExperimentConfig (auto-generated by Pydantic)."""
    return ExperimentConfig.model_json_schema()


@router.get("/{name}/config")
def default_config(name: str) -> dict[str, Any]:
    """Return the default ExperimentConfig for a registered experiment."""
    try:
        exp = get_experiment(name)
    except KeyError as exc:
        raise HTTPException(status_code=404, detail=str(exc)) from exc
    return exp.default_config().model_dump(exclude_none=True)


# ── Execution ───────────────────────────────────────────────────────────


@router.post("/run")
def run_experiment(config: ExperimentConfig) -> dict[str, Any]:
    """Run a single experiment and return the full ExperimentResult."""
    result: ExperimentResult = engine_run(config)
    return result.model_dump()


@router.post("/sweep")
def run_sweep(manifest: SweepManifest) -> list[dict[str, Any]]:
    """Run a parameter sweep and return a list of ExperimentResults."""
    results = engine_sweep(manifest)
    return [r.model_dump() for r in results]
