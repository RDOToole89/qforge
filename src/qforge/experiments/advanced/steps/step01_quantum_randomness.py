"""Step 1: Quantum Random Numbers — True randomness from physics.

WHAT YOU'LL LEARN:
  Classical "random" numbers are pseudo-random — generated by deterministic
  algorithms. Quantum randomness is FUNDAMENTALLY different: it comes from
  the measurement of a superposition state, and no algorithm, no matter
  how powerful, can predict the outcome.

  This is your first quantum "application" — and it's already better
  than anything classical computers can do.

WHY THIS MATTERS FOR EXPERIMENTS:
  Every quantum experiment uses shots (repeated measurements). The
  randomness in those shots is not noise or imprecision — it's the
  actual physics. Understanding this is foundational for interpreting
  every experiment you'll run.

THE EXPERIMENT:
  Generate N random bits by putting N qubits into superposition and
  measuring. Each bit is guaranteed to be truly random by quantum
  mechanics. We verify the randomness by checking:
  - Uniform distribution (each outcome equally likely)
  - No correlations between bits (independence)

FRAMEWORK SKILL:
  You'll learn to use ExperimentConfig with custom circuits and
  inspect raw measurement counts from the result object.

CIRCUIT (4-qubit version):
  q0: ─H── M
  q1: ─H── M
  q2: ─H── M
  q3: ─H── M

  Each qubit independently in superposition.
  Each measurement is a truly random bit.

TRY IT:
    from qforge.experiments.advanced.steps.step01_quantum_randomness import quantum_randomness

    result = quantum_randomness.run()
    result = quantum_randomness.run_bit_independence_test()
"""

from __future__ import annotations

from qiskit import QuantumCircuit

from qforge.engine.models import ExperimentConfig, ExperimentResult
from qforge.experiments.base import BaseExperiment


class QuantumRandomnessExperiment(BaseExperiment):
    """Step 1: Generate and verify true quantum random numbers."""

    name = "adv_01_quantum_randomness"
    description = "Step 1: True randomness — generate provably random bits from quantum measurement"
    metrics_hint = "Near 0 is the point: independent coins, no hidden pattern in the bits."

    def default_config(self) -> ExperimentConfig:
        """Return the default configuration for this experiment."""
        qc = QuantumCircuit(8, 8)
        for i in range(8):
            qc.h(i)
        qc.measure(range(8), range(8))
        return ExperimentConfig(
            num_qubits=8,
            state_type="CUSTOM",
            shots=4096,
            noise_enabled=False,
            custom_params={"source": "circuit", "circuit": qc},
            visualization_type=["histogram", "circuit"],
            metrics=["structure_score", "total_correlation"],
        )

    def run_bit_independence_test(self) -> list[ExperimentResult]:
        """Run at 1, 2, 4, 8 qubits to verify independence scales."""
        results = []
        for n in [1, 2, 4, 8]:
            qc = QuantumCircuit(n, n)
            for i in range(n):
                qc.h(i)
            qc.measure(range(n), range(n))
            results.append(
                self.run(
                    {
                        "num_qubits": n,
                        "custom_params": {"source": "circuit", "circuit": qc},
                    }
                )
            )
        return results


quantum_randomness = QuantumRandomnessExperiment()
